-- BASE-03 (KAN-2) 계정·로그인 세션 표. 로그인 서버 배포 전 기존 DB에 독립적으로 적용한다.
-- 절차 및 롤백: docs/base03-accounts-rollout.md
--
-- 새 표 6개(users, user_identities, user_consents, user_password_credentials, auth_sessions,
-- auth_login_attempts)만 만든다.
-- 기존 표와 owner_id 컬럼은 건드리지 않는다(FK 연결은 후속 작업). 대신 users.id 시퀀스를 기존
-- owner_id 최댓값 다음(최소 1000)으로 옮겨 새 계정이 기존 데이터를 물려받지 않게 한다(1-1).
-- 결과는 app/db/schema.sql과 같은 정의다. 이미 있는 표가 기대 정의와 다르면 예외로 전체를
-- 되돌린다. 다시 실행해도 데이터와 정의가 바뀌지 않는다.
BEGIN;
SET LOCAL lock_timeout = '3s';
SET LOCAL statement_timeout = '60s';
SET LOCAL search_path = pg_catalog, public;

-- 새 표라 잠글 기존 표가 없다. 같은 배포 작업이 동시에 돌지 않도록 트랜잭션 잠금을 잡는다.
SELECT pg_advisory_xact_lock(hashtext('charchat.base03_accounts'));

-- 표 정의 요약(종류, 컬럼, NOT NULL 외 제약, 제약 외 인덱스). 기대값과 문자열로 비교한다.
CREATE OR REPLACE FUNCTION pg_temp.base03_signature(rel regclass) RETURNS text
LANGUAGE sql STABLE AS $sig$
    SELECT concat_ws(E'\n',
        (SELECT format('rel %s %s', c.relkind, c.relpersistence) FROM pg_class c WHERE c.oid = rel),
        (SELECT string_agg(format('col %s %s%s%s%s', a.attname,
                    format_type(a.atttypid, a.atttypmod),
                    CASE WHEN a.attnotnull THEN ' NOT NULL' END,
                    CASE a.attidentity WHEN 'a' THEN ' IDENTITY ALWAYS'
                                       WHEN 'd' THEN ' IDENTITY BY DEFAULT' END,
                    ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid)), E'\n' ORDER BY a.attnum)
           FROM pg_attribute a
           LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
           WHERE a.attrelid = rel AND a.attnum > 0 AND NOT a.attisdropped),
        (SELECT string_agg(format('con %s %s', c.conname, pg_get_constraintdef(c.oid)), E'\n'
                    ORDER BY c.conname)
           FROM pg_constraint c WHERE c.conrelid = rel AND c.contype <> 'n'),
        (SELECT string_agg(format('idx %s', pg_get_indexdef(i.indexrelid)), E'\n'
                    ORDER BY pg_get_indexdef(i.indexrelid))
           FROM pg_index i
           WHERE i.indrelid = rel AND NOT EXISTS (
               SELECT 1 FROM pg_constraint c WHERE c.conindid = i.indexrelid AND c.conrelid = rel)));
$sig$;

CREATE OR REPLACE FUNCTION pg_temp.base03_expect(rel text, expected text) RETURNS void
LANGUAGE plpgsql AS $expect$
DECLARE
    actual text := pg_temp.base03_signature(rel::regclass);
BEGIN
    IF actual IS DISTINCT FROM expected THEN
        RAISE EXCEPTION 'BASE-03: unexpected % definition', rel
            USING DETAIL = format(E'expected:\n%s\nactual:\n%s', expected, actual);
    END IF;
END;
$expect$;

-- 1. 계정
CREATE TABLE IF NOT EXISTS public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'active', 'deleted')),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    onboarded_at timestamptz,
    deleted_at timestamptz,
    CONSTRAINT users_status_times CHECK (
        (status = 'pending' AND onboarded_at IS NULL AND deleted_at IS NULL)
        OR (status = 'active' AND onboarded_at IS NOT NULL AND deleted_at IS NULL)
        OR (status = 'deleted' AND deleted_at IS NOT NULL)
    )
);
SELECT pg_temp.base03_expect('public.users', $exp$rel r p
col id bigint NOT NULL IDENTITY BY DEFAULT
col status text NOT NULL DEFAULT 'pending'::text
col created_at timestamp with time zone NOT NULL DEFAULT clock_timestamp()
col onboarded_at timestamp with time zone
col deleted_at timestamp with time zone
con users_pkey PRIMARY KEY (id)
con users_status_check CHECK ((status = ANY (ARRAY['pending'::text, 'active'::text, 'deleted'::text])))
con users_status_times CHECK ((((status = 'pending'::text) AND (onboarded_at IS NULL) AND (deleted_at IS NULL)) OR ((status = 'active'::text) AND (onboarded_at IS NOT NULL) AND (deleted_at IS NULL)) OR ((status = 'deleted'::text) AND (deleted_at IS NOT NULL))))$exp$);

-- 1-1. 새 계정 id가 기존 owner_id 데이터와 겹치지 않게 users.id 시퀀스를 앞으로 옮긴다.
-- 기존 기능은 owner_id = users.id로 권한을 정하므로, 계정 없이 쌓인 owner_id(예전 X-User-Id)와
-- 같은 id의 새 계정은 그 데이터를 물려받는다. owner_id 컬럼이 있는 모든 public 표(나중에 추가된
-- 표 포함)와 users의 최댓값 + 1, 그리고 1000(공용 DB에서 손으로 쓰는 개발용 X-User-Id 1~999 보호)
-- 중 큰 값으로 맞춘다. 앞으로만 옮기며 재실행해도 뒤로 가지 않는다.
DO $base03_seq$
DECLARE
    seq text := pg_get_serial_sequence('public.users', 'id');
    next_id bigint;
    floor_id bigint := 1000;
    found bigint;
    owner_table record;
BEGIN
    EXECUTE format('SELECT CASE WHEN is_called THEN last_value + 1 ELSE last_value END FROM %s', seq)
        INTO next_id;
    FOR owner_table IN
        SELECT n.nspname, c.relname
        FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        JOIN pg_attribute a ON a.attrelid = c.oid
        WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p') AND NOT c.relispartition
          AND a.attname = 'owner_id' AND a.attnum > 0 AND NOT a.attisdropped
          AND a.atttypid IN ('smallint'::regtype, 'integer'::regtype, 'bigint'::regtype)
    LOOP
        EXECUTE format('SELECT max(owner_id)::bigint FROM %I.%I', owner_table.nspname,
                       owner_table.relname)
            INTO found;
        floor_id := GREATEST(floor_id, COALESCE(found, 0) + 1);
    END LOOP;
    SELECT GREATEST(floor_id, COALESCE(max(id), 0) + 1) INTO floor_id FROM public.users;
    IF floor_id > next_id THEN
        PERFORM setval(seq, floor_id, false);
    END IF;
END;
$base03_seq$;

-- 2. 외부 로그인 연결
-- 인덱스가 있는 표는 표가 없을 때만 표와 인덱스를 함께 만든다(다른 정의의 표에 인덱스를 붙이지 않음).
DO $base03$
BEGIN
    IF to_regclass('public.user_identities') IS NULL THEN
        CREATE TABLE public.user_identities (
            id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
            provider text NOT NULL CHECK (provider IN ('kakao', 'google', 'apple', 'dev')),
            provider_user_id text NOT NULL
                CHECK (provider_user_id <> '' AND length(provider_user_id) <= 255),
            created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
            last_login_at timestamptz NOT NULL DEFAULT clock_timestamp(),
            CONSTRAINT user_identities_provider_subject_key UNIQUE (provider, provider_user_id)
        );
        CREATE INDEX user_identities_user_idx ON public.user_identities(user_id);
    END IF;
END;
$base03$;
SELECT pg_temp.base03_expect('public.user_identities', $exp$rel r p
col id bigint NOT NULL IDENTITY ALWAYS
col user_id bigint NOT NULL
col provider text NOT NULL
col provider_user_id text NOT NULL
col created_at timestamp with time zone NOT NULL DEFAULT clock_timestamp()
col last_login_at timestamp with time zone NOT NULL DEFAULT clock_timestamp()
con user_identities_pkey PRIMARY KEY (id)
con user_identities_provider_check CHECK ((provider = ANY (ARRAY['kakao'::text, 'google'::text, 'apple'::text, 'dev'::text])))
con user_identities_provider_subject_key UNIQUE (provider, provider_user_id)
con user_identities_provider_user_id_check CHECK (((provider_user_id <> ''::text) AND (length(provider_user_id) <= 255)))
con user_identities_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
idx CREATE INDEX user_identities_user_idx ON public.user_identities USING btree (user_id)$exp$);

