-- 4. 로그인 세션(리프레시 토큰의 sha256 해시. 액세스 토큰은 JWT라 저장하지 않는다)
DO $base03$
BEGIN
    IF to_regclass('public.auth_sessions') IS NULL THEN
        CREATE TABLE public.auth_sessions (
            id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
            client_platform text NOT NULL CHECK (client_platform IN ('ios', 'android', 'web')),
            refresh_token_hash bytea NOT NULL UNIQUE,
            refresh_expires_at timestamptz NOT NULL,
            previous_refresh_hash bytea UNIQUE,
            rotated_at timestamptz,
            created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
            last_used_at timestamptz NOT NULL DEFAULT clock_timestamp(),
            revoked_at timestamptz,
            revoke_reason text
                CHECK (revoke_reason IN ('logout', 'refresh_reuse', 'account_deleted', 'expired')),
            CONSTRAINT auth_sessions_revoke_pair CHECK ((revoked_at IS NULL) = (revoke_reason IS NULL))
        );
        CREATE INDEX auth_sessions_active_user_idx
            ON public.auth_sessions(user_id) WHERE revoked_at IS NULL;
    END IF;
END;
$base03$;
