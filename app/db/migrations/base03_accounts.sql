con auth_login_attempts_redirect_fields CHECK (((flow = 'native'::text) OR ((state_hash IS NOT NULL) AND (app_code_challenge IS NOT NULL) AND (return_to IS NOT NULL))))
con auth_login_attempts_state_hash_key UNIQUE (state_hash)
con auth_login_attempts_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE$exp$);

