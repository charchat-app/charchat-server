-- 5. 외부 제공자 로그인 시도(후속 제공자 로그인 작업에서 사용)
CREATE TABLE IF NOT EXISTS public.auth_login_attempts (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    provider text NOT NULL CHECK (provider IN ('kakao', 'google', 'apple', 'dev')),
    flow text NOT NULL CHECK (flow IN ('redirect', 'native')),
    client_platform text NOT NULL CHECK (client_platform IN ('ios', 'android', 'web')),
    state_hash bytea UNIQUE,
    nonce text NOT NULL,
    provider_code_verifier text,
    app_code_challenge text,
    return_to text,
    expires_at timestamptz NOT NULL,
    login_code_hash bytea UNIQUE,
    user_id bigint REFERENCES public.users(id) ON DELETE CASCADE,
    completed_at timestamptz,
    consumed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT auth_login_attempts_redirect_fields CHECK (
        flow = 'native'
        OR (state_hash IS NOT NULL AND app_code_challenge IS NOT NULL AND return_to IS NOT NULL)
    )
);
