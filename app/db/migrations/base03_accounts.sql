-- 3-1. 이메일·비밀번호 로그인 정보(bcrypt 해시)
CREATE TABLE IF NOT EXISTS public.user_password_credentials (
    user_id bigint PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
