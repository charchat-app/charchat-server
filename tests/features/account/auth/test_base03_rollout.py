"""BASE-03 배포 SQL(base03_accounts.sql): 기존 DB에 적용하면 schema.sql과 같은 정의가 되고,
다시 실행해도 데이터·정의가 같으며, 같은 이름의 다른 정의가 있으면 전체를 되돌린다."""

from pathlib import Path

import psycopg
import pytest
from psycopg.pq import TransactionStatus

from tests.features.account.account_helpers import ME, active_login, bearer

ROOT = Path(__file__).resolve().parents[4]
MIGRATION = ROOT / "app/db/migrations/base03_accounts.sql"
BASE03_TABLES = (
    "users",
    "user_identities",
    "user_consents",
    "auth_sessions",
    "auth_login_attempts",
)


def schema_snapshot(db):
    """BASE-03 표의 컬럼·제약·인덱스 정의."""
    columns = db.execute(
        """SELECT table_name, column_name, data_type, is_nullable, column_default,
                  is_identity, identity_generation, ordinal_position
           FROM information_schema.columns
           WHERE table_schema = 'public' AND table_name = ANY(%s)
           ORDER BY table_name, column_name""",
        (list(BASE03_TABLES),),
    ).fetchall()
    constraints = db.execute(
        """SELECT conrelid::regclass::text AS tbl, conname, pg_get_constraintdef(oid) AS def
           FROM pg_constraint
           WHERE conrelid = ANY(ARRAY(SELECT to_regclass(t) FROM unnest(%s::text[]) t))
           ORDER BY 1, 2""",
        (list(BASE03_TABLES),),
    ).fetchall()
    indexes = db.execute(
        """SELECT tablename, indexname, indexdef FROM pg_indexes
           WHERE schemaname = 'public' AND tablename = ANY(%s) ORDER BY 1, 2""",
        (list(BASE03_TABLES),),
    ).fetchall()
    return columns, constraints, indexes


def existing_tables(db) -> list[str]:
    rows = db.execute(
        "SELECT t FROM unnest(%s::text[]) t WHERE to_regclass('public.' || t) IS NOT NULL",
        (list(BASE03_TABLES),),
    ).fetchall()
    return [row["t"] for row in rows]


def drop_base03_tables(db) -> None:
    """BASE-03 표를 지워 origin/dev(배포 전) 스키마 상태로 되돌린다."""
    db.execute(f"DROP TABLE IF EXISTS {', '.join(reversed(BASE03_TABLES))}")


@pytest.fixture
def migration(db):
    """마이그레이션 SQL. 테스트가 중간에 실패해도 다음 테스트가 쓸 스키마로 되돌린다."""
    sql = MIGRATION.read_text(encoding="utf-8")
    yield sql
    if db.info.transaction_status != TransactionStatus.IDLE:
        db.execute("ROLLBACK")
    if len(existing_tables(db)) != len(BASE03_TABLES):
        drop_base03_tables(db)
        db.execute(sql)


def test_migration_on_pre_base03_db_matches_schema_and_is_idempotent_BASE_03(db, migration):
    expected = schema_snapshot(db)
    db.execute(
        "INSERT INTO stories (owner_id, title) VALUES (7, '기존 스토리')"
    )  # 기존 데이터는 그대로
    drop_base03_tables(db)
    assert existing_tables(db) == []

    db.execute(migration)
    assert schema_snapshot(db) == expected
    db.execute(migration)  # 재실행해도 같다
    assert schema_snapshot(db) == expected
    assert db.execute("SELECT owner_id, title FROM stories").fetchall() == [
        {"owner_id": 7, "title": "기존 스토리"}
    ]


def test_migration_rerun_keeps_accounts_and_sessions_BASE_03(db, client, migration):
    tokens = active_login(client, "alice")
    before = [db.execute(f"SELECT * FROM {table} ORDER BY 1").fetchall() for table in BASE03_TABLES]
    db.execute(migration)
    after = [db.execute(f"SELECT * FROM {table} ORDER BY 1").fetchall() for table in BASE03_TABLES]
    assert after == before
    assert client.get(ME, headers=bearer(tokens["access_token"])).json()["status"] == "active"


@pytest.mark.parametrize(
    ("prepare", "message"),
    [
        (
            # 이전 초안처럼 정의가 다른 같은 이름의 표는 건너뛰지 않고 거절한다.
            "CREATE TABLE users (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, email text)",
            "unexpected public.users definition",
        ),
        (
            """CREATE TABLE users (
                   id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                   status text NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending', 'active', 'deleted')),
                   created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
                   onboarded_at timestamptz,
                   deleted_at timestamptz,
                   CONSTRAINT users_status_times CHECK (
                       (status = 'pending' AND onboarded_at IS NULL AND deleted_at IS NULL)
                       OR (status = 'active' AND onboarded_at IS NOT NULL AND deleted_at IS NULL)
                       OR (status = 'deleted' AND deleted_at IS NOT NULL)
                   )
               );
               CREATE TABLE auth_sessions (id bigint PRIMARY KEY, token text)""",
            "unexpected public.auth_sessions definition",
        ),
    ],
)
def test_migration_aborts_and_rolls_back_on_unexpected_definition_BASE_03(
    db, migration, prepare, message
):
    drop_base03_tables(db)
    db.execute(prepare)
    prepared = existing_tables(db)
    with pytest.raises(psycopg.errors.RaiseException, match=message):
        db.execute(migration)
    db.execute("ROLLBACK")
    # 전체가 되돌아가 미리 있던 표 외에는 하나도 생기지 않았다.
    assert existing_tables(db) == prepared
    drop_base03_tables(db)


def test_migration_aborts_when_existing_table_lacks_index_BASE_03(db, migration):
    """표만 있고 인덱스가 빠진 상태도 정의 불일치로 보고 고치지 않은 채 중단한다."""
    db.execute("DROP INDEX auth_sessions_active_user_idx")
    with pytest.raises(
        psycopg.errors.RaiseException, match="unexpected public.auth_sessions definition"
    ):
        db.execute(migration)
    db.execute("ROLLBACK")
    assert db.execute("SELECT to_regclass('auth_sessions_active_user_idx') AS i").fetchone() == {
        "i": None
    }
    drop_base03_tables(db)
